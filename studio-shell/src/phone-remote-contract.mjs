/* UI display qualification only. This cannot grant Ward or Switchboard authority. */
const APP = 'personal:movie-night';

export function acceptedRemoteCapability(data) {
  if (data?.schema !== 'movie-night.phone-remote-capabilities/v1'
      || data?.application_ref !== APP
      || data?.state !== 'PAIRING_READY'
      || data?.transport !== 'https') return null;
  try {
    const target = new URL(data.pairing_origin);
    if (target.protocol !== 'https:' || target.username || target.password
        || target.search || target.hash || target.pathname !== '/') return null;
    return Object.freeze({ origin: target.origin, app: APP });
  } catch { return null; }
}

export function acceptedRemoteInvitation(data, capability, now = Date.now()) {
  if (!capability || data?.schema !== 'movie-night.phone-remote-pairing/v1'
      || data?.state !== 'OFFERED' || data?.application_ref !== APP
      || data?.method !== 'single-use-approved-session') return null;
  try {
    const link = new URL(data.url);
    const expiry = Date.parse(data.expires_at);
    if (link.origin !== capability.origin || link.username || link.password
        || link.hash || !link.pathname.startsWith('/remote/pair/')
        || !Number.isFinite(expiry) || expiry <= now || expiry - now > 120_000) return null;
    // The QR image is generated by the admitted private pairing service, not a
    // third-party QR website. Never render arbitrary SVG or provider-supplied HTML.
    const image = data.qr_png;
    if (typeof image !== 'string' || image.length < 200 || image.length > 130_000
        || !/^data:image\/png;base64,[A-Za-z0-9+/]+={0,2}$/.test(image)) return null;
    return Object.freeze({ url: link.toString(), image, expiresAt: expiry });
  } catch { return null; }
}

